"""Write figure-reproduction/results.json, the repository's results-check file (tools/check_results.py):
every value our run gives for a published bar or box median, each method's power in each setting,
and the pixel scores (comparison.json, summary.json) become entries whose expected value is the
committed output, so CI catches any drift of the reproduction.

usage: make_results_check.py COMMITTED_OUTPUT_DIR OUT_JSON
"""
import json
import sys
from pathlib import Path

committed, out = sys.argv[1:3]
comp = json.loads((Path(committed) / "comparison.json").read_text())
results = []
for meth, fields in comp["fig2"]["values"].items():
    for i, f in enumerate(fields):
        results.append({"id": f"fig2.{meth}.{i}", "label": f"Fig. 2, {meth}, {f['name']} (paper {f['expected']})",
                        "file": "comparison.json", "path": f"fig2.values.{meth}.{i}.observed",
                        "expected": f["observed"], "tolerance": {"abs": 1e-9}})
for i, f in enumerate(comp["fig3"]["medians"]):
    results.append({"id": f"fig3.median.{i}", "label": f"Fig. 3, median selected, {f['name']} (paper {f['expected']})",
                    "file": "comparison.json", "path": f"fig3.medians.{i}.observed",
                    "expected": f["observed"], "tolerance": {"abs": 1e-9}})
for fig in ("fig2", "fig3"):
    p = comp[fig]["pixels"]
    for k in ("published_near_ours", "ours_near_published"):
        results.append({"id": f"{fig}.{k}", "label": f"{fig} pixels, {k.replace('_', ' ')} within 2 px",
                        "file": "comparison.json", "path": f"{fig}.pixels.{k}",
                        "expected": p[k], "tolerance": {"abs": 1e-6}})
doc = {"paper": "PMC2648748",
       "title": "Jiang R, Tang W, Wu X, Fu W. A random forest approach to the detection of epistatic interactions in case-control studies. BMC Bioinformatics 10(Suppl 1):S65 (2009)",
       "about": "Our value for every published bar and box median that the reproduction compares, and the pixel scores of Figs 2 and 3. CI reruns the pipeline (three simulated data sets from scratch; the rest from the committed per-data-set records in output/sim) and checks each value with tools/check_results.py. Generated by pipeline/make_results_check.py from the committed comparison.json. The verdicts are in ../results.json.",
       "committed_paths": {"": "output/"},
       "results": results}
Path(out).write_text(json.dumps(doc, indent=2) + "\n")
print(f"{len(results)} entries")
