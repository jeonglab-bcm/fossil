"""Write figure-reproduction/results.json, the repository's results-check file (tools/check_results.py):
every value our run gives for a published bar or curve point (comparison.json) becomes an entry whose
expected value is the committed output, so CI catches any drift of the reproduction.

  make_results_check.py COMMITTED_OUTPUT_DIR OUT_JSON
"""
import json
import sys
from pathlib import Path

committed, out = sys.argv[1:3]
comp = json.load(open(Path(committed) / "comparison.json"))
results = []
for it in comp["item_list"]:
    key = it["key"]
    src = next(k for k in comp["items"] if k.replace(".", "") == key)
    for i, f in enumerate(comp["items"][src]["fields"]):
        results.append({"id": f"{src}.{i}", "label": f"{src}, {f['name']} (paper {f['expected']})",
                        "file": "comparison.json", "path": f"item_list.key={key}.fields.{i}.observed",
                        "expected": float(f["observed"]), "tolerance": {"abs": 1e-9}})
doc = {"paper": "PMC2666661",
       "title": "Meng YA, Yu Y, Cupples LA, Farrer LA, Lunetta KL. Performance of random forest when SNPs are in linkage disequilibrium. BMC Bioinformatics 10:78 (2009)",
       "about": "Our value for every published bar and curve point that the reproduction compares. CI reruns the pipeline (a few simulation replicates from scratch; the rest from the committed per-replicate statistics in output/sim) and checks each value with tools/check_results.py. Generated by pipeline/make_results_check.py from the committed comparison.json.",
       "committed_paths": {"": "output/"},
       "results": results}
Path(out).write_text(json.dumps(doc, indent=2) + "\n")
print(f"{len(results)} entries")
