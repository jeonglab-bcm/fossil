"""Fill the Results section of the paper's READMEs from results.json (nothing typed by hand).

  make_readme.py RESULTS_JSON PAGE_JSON README.md [README.md ...]

Replaces the text between <!--RESULTS--> and <!--/RESULTS--> (or the bare <!--RESULTS--> marker) with
the summary line, one row per result (Additional file 1's 32 figures as one row) and the claims line.
"""
import json
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
from check_results import field_matches  # noqa: E402

WORD = {"exact": "exact", "agrees": "agrees", "partly": "partly", "inconclusive": "inconclusive",
        "differs": "differs", "not_attempted": "not attempted"}


def first_sentence(s):
    m = re.match(r"(.+?(?<!Fig)(?<!Figs)\.)(\s|$)", s or "")
    return m.group(1) if m else (s or "")


def measure(it):
    if it["method"] == "values":
        f = it["values"]["fields"]
        exc = {e["field"] for e in it["values"].get("exceptions", [])}
        counted = [x for x in f if x["name"] not in exc]
        hits = sum(field_matches(x, it["values"].get("tolerance")) for x in counted)
        return f"{hits} of {len(counted)} values as printed" + (f" ({len(exc)} paper errors set aside)" if exc else "")
    if it["method"] == "pixels":
        p = it["pixels"]
        best = max(c["score"] for c in p["controls"])
        return f"{100 * min(p['published_near_ours'], p['ours_near_published']):.1f}% within 2 px (best control {100 * best:.1f}%, pass {100 * p['threshold']:.0f}%)"
    if it["method"] == "check":
        return first_sentence(it["check"]["detail"])
    return ""


def main(results, page, *readmes):
    R = json.loads(Path(results).read_text())
    P = json.loads(Path(page).read_text())
    s = R["summary"]
    lines = ["<!--RESULTS-->",
             f"<!-- generated by figure-reproduction/pipeline/make_readme.py from results.json -->", "",
             f"{s['items']} results: {s['exact']} exact, {s['agrees']} agree, {s['partly']} partly agree, "
             f"{s['inconclusive']} inconclusive, {s['differs']} differ, {s['not_attempted']} not attempted; "
             f"{s['open_causes']} open causes.", "",
             "| Result | Verdict | Ours against the paper | Why |", "| --- | --- | --- | --- |"]
    supp_done = False
    for it in R["items"]:
        if it["id"].startswith("figS"):
            if supp_done:
                continue
            supp_done = True
            lines.append("| Additional file 1, Figs S1-S32 | not attempted | computed, not drawn | "
                         + first_sentence(it["cause"]["summary"][len("Not drawn. "):]) + " |")
            continue
        why = first_sentence((it.get("cause") or {}).get("summary", ""))
        lines.append(f"| {it['label']} | {WORD[it['verdict']]} | {measure(it)} | {why} |")
    lines += ["", P["claims_line"], "<!--/RESULTS-->"]
    block = "\n".join(lines)
    for rd in readmes:
        t = Path(rd).read_text()
        t = re.sub(r"<!--RESULTS-->.*?<!--/RESULTS-->", lambda m: block, t, flags=re.S) if "<!--/RESULTS-->" in t \
            else t.replace("<!--RESULTS-->", block)
        Path(rd).write_text(t)
        print("wrote", rd)


if __name__ == "__main__":
    main(*sys.argv[1:])
