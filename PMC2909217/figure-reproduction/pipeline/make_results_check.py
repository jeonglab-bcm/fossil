"""Write figure-reproduction/results.json, the repository's results-check file (tools/check_results.py):
the numbers the reproduction stands on, with the committed outputs as expected values, so CI catches
any drift. The verdicts themselves are in ../results.json (paper2repro/results/v1).

  make_results_check.py COMMITTED_OUTPUT_DIR OUT_JSON
"""
import json
import sys
from pathlib import Path

committed, out = sys.argv[1:3]
c = Path(committed)
roc = json.load(open(c / "roc.json"))
comp = json.load(open(c / "comparison.json"))
t1 = json.load(open(c / "table1.json"))
results = []
for key, v in roc["curves"].items():
    results.append({"id": f"roc.{key}", "label": f"Area under the ROC curve, {key} (mean of 5 repeats)",
                    "file": "roc.json", "path": f"curves.{key}.auc_mean", "expected": v["auc_mean"],
                    "tolerance": {"abs": 1e-6}})
    results.append({"id": f"tpr09.{key}", "label": f"TPR at FPR 0.09, {key} (paper's best SSL: 0.92)",
                    "file": "roc.json", "path": f"curves.{key}.tpr_at_fpr_mean.9",
                    "expected": v["tpr_at_fpr_mean"][9], "tolerance": {"abs": 1e-6}})
for key in ("fig2", "fig3", "fig4", "fig5"):
    for side in ("published_near_ours", "ours_near_published"):
        results.append({"id": f"{key}.{side}", "label": f"{key}: {side.replace('_', ' ')} within 2 px",
                        "file": "comparison.json", "path": f"{key}.{side}", "expected": comp[key][side]})
for row in t1["rows"]:
    for net in ("binary", "weighted"):
        results.append({"id": f"table1.{row['id']}.{net}.D", "label": f"Table 1, {row['id']}, {net}, KS D",
                        "file": "table1.json", "path": f"rows.id={row['id']}.{net}.D", "expected": row[net]["D"],
                        "tolerance": {"rel": 1e-6}})
doc = {"paper": "PMC2909217",
       "title": "You ZH, Yin Z, Han K, Huang DS, Zhou X. A semi-supervised learning approach to predict synthetic genetic interactions by combining functional and topological properties of functional gene network. BMC Bioinformatics 11:343 (2010)",
       "about": "The numbers the reproduction stands on: areas under our ROC curves and TPR at FPR 0.09 (Figs 2-5), the pixel scores of Figs 2-5, and our Table 1 KS statistics. CI reruns the whole pipeline and checks each value with tools/check_results.py. Generated by pipeline/make_results_check.py from the committed outputs; the verdicts are in ../results.json.",
       "committed_paths": {"": "output/"},
       "results": results}
Path(out).write_text(json.dumps(doc, indent=2) + "\n")
print(f"{len(results)} entries")
