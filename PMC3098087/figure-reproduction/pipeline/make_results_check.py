"""Write figure-reproduction/results.json, the repository's results-check file (tools/check_results.py):
our value for every printed cell of Additional files 1, 3, 13 and 14, the number of matching points
of every figure item, every claim and the port check, each expected to equal the committed output,
so CI catches any drift.

Usage: make_results_check.py OUTPUT_DIR OUT_JSON
"""
import json
import sys
from pathlib import Path

out_dir, out = Path(sys.argv[1]), sys.argv[2]
comp = json.load(open(out_dir / "comparison.json"))
claims = json.load(open(out_dir / "claims.json"))
port = json.load(open(out_dir / "port_check.json"))
NUM = {"rel": 1e-9, "abs": 1e-12}
results = []


def add(id_, label, file, path, value):
    e = {"id": id_, "label": label, "file": file, "path": path, "expected": value}
    if isinstance(value, float):
        e["tolerance"] = NUM
    results.append(e)


for key, block in comp.items():
    add(f"{key}.matched", f"{key}: values within tolerance (of {block['n_fields']})", "comparison.json", f"{key}.matched", block["matched"])
    if key in ("af1", "af3", "af13", "af14"):
        for i, f in enumerate(block["fields"]):
            if isinstance(f.get("observed"), (int, float)):
                add(f"{key}.{i}", f"{key}, {f['name']} (paper {f['expected']})", "comparison.json", f"{key}.fields.{i}.observed", f["observed"])
for cid, c in claims.items():
    for i, f in enumerate(c["fields"]):
        if f.get("observed") is not None:
            add(f"{cid}.{i}", f"{cid}, {f['name']} (paper {f['expected']})", "claims.json", f"{cid}.fields.{i}.observed", f["observed"])
for k in ("dlda_agree", "dqda_agree", "test_samples", "passed"):
    add(f"port.{k}", f"port check: {k.replace('_', ' ')}", "port_check.json", k, port[k])
doc = {"paper": "PMC3098087",
       "title": "Blagus R, Lusa L. Class prediction for high-dimensional class-imbalanced data. BMC Bioinformatics 11:523 (2010)",
       "about": "Our value for every printed cell of Additional files 1, 3, 13 and 14, the count of matching points of every figure item, every claim and the DLDA/DQDA port check. CI reruns the pipeline and checks each value with tools/check_results.py. Generated by pipeline/make_results_check.py from the committed outputs.",
       "committed_paths": {"": "output/"},
       "results": results}
Path(out).write_text(json.dumps(doc, indent=1) + "\n")
print(f"{out}: {len(results)} entries", file=sys.stderr)
