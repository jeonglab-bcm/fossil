"""Write figure-reproduction/results.json, the repository's results-check file (tools/check_results.py):
every value our run gives for a published table cell, p-value, AUC, claim or figure score
(comparison.json) becomes an entry whose expected value is the committed output, so CI catches
any drift of the reproduction.

  make_results_check.py COMMITTED_OUTPUT_DIR OUT_JSON
"""
import json
import sys
from pathlib import Path

committed, out = sys.argv[1:3]
comp = json.load(open(Path(committed) / "comparison.json"))["items"]
results = []
for key, it in comp.items():
    k = key.replace(".", "_")
    if it.get("method") == "values":
        for i, f in enumerate(it["values"]["fields"]):
            if f["observed"] is None:
                continue
            e = {"id": f"{key}.{i}", "label": f"{key}, {f['name']} (paper {f['expected']})",
                 "file": "comparison.json", "path": f"item_list.key={k}.values.fields.{i}.observed",
                 "expected": f["observed"]}
            if isinstance(f["observed"], float):
                e["tolerance"] = {"abs": 1e-9}
            results.append(e)
    elif it.get("method") == "pixels":
        for side in ("published_near_ours", "ours_near_published"):
            results.append({"id": f"{key}.{side}", "label": f"{key}, {side.replace('_', ' ')}",
                            "file": "comparison.json", "path": f"item_list.key={k}.pixels.{side}",
                            "expected": it["pixels"][side], "tolerance": {"abs": 1e-9}})
    elif it.get("method") == "check":
        results.append({"id": f"{key}.passed", "label": f"{key}: {it['check']['detail'][:120]}",
                        "file": "comparison.json", "path": f"item_list.key={k}.check.passed",
                        "expected": it["check"]["passed"]})
doc = {"paper": "PMC4168973",
       "title": "Huang S, Yee C, Ching T, Yu H, Garmire LX. A novel model to combine clinical and pathway-based transcriptomic information for the prognosis prediction of breast cancer. PLoS Comput Biol 10(9):e1003851 (2014)",
       "about": "Our value for every Table 1 cell, Fig. 1 test, Table 2 and 3 value, model p-value and AUC (Figs 3 to 6, S3), claim and figure score that the reproduction compares. CI reruns the pipeline and checks each value with tools/check_results.py. Generated by pipeline/make_results_check.py from the committed comparison.json.",
       "committed_paths": {"": "output/"},
       "results": results}
Path(out).write_text(json.dumps(doc, indent=2) + "\n")
print(f"{len(results)} entries")
