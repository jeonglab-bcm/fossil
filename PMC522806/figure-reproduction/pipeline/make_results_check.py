"""Write figure-reproduction/results.json, the repository's results-check file (tools/check_results.py):
every value our run gives for a published table cell, bar, score or claim (comparison.json) becomes an
entry whose expected value is the committed output, so CI catches any drift of the reproduction.

  make_results_check.py COMMITTED_OUTPUT_DIR OUT_JSON
"""
import json
import sys
from pathlib import Path

committed, out = sys.argv[1:3]
comp = json.load(open(Path(committed) / "comparison.json"))["items"]
results = []
for key, it in comp.items():
    if it.get("method") == "values":
        for i, f in enumerate(it["values"]["fields"]):
            if f["observed"] is None:
                continue
            results.append({"id": f"{key}.{i}", "label": f"{key}, {f['name']} (paper {f['expected']})",
                            "file": "comparison.json", "path": f"item_list.key={key.replace('.', '_')}.values.fields.{i}.observed",
                            "expected": f["observed"]})
    elif it.get("method") == "pixels":
        for side in ("published_near_ours", "ours_near_published"):
            results.append({"id": f"{key}.{side}", "label": f"{key}, {side.replace('_', ' ')}",
                            "file": "comparison.json", "path": f"item_list.key={key.replace('.', '_')}.pixels.{side}",
                            "expected": it["pixels"][side], "tolerance": {"abs": 1e-9}})
doc = {"paper": "PMC522806",
       "title": "Liu B, Cui Q, Jiang T, Ma S. A combinational feature selection and ensemble neural network method for classification of gene expression data. BMC Bioinformatics 5:136 (2004)",
       "about": "Our value for every published table cell, Fig. 3 and 4 bar and claim that the reproduction compares. CI reruns the pipeline (the slow folds sampled) and checks each value with tools/check_results.py. Generated by pipeline/make_results_check.py from the committed comparison.json.",
       "committed_paths": {"": "output/"},
       "results": results}
Path(out).write_text(json.dumps(doc, indent=2) + "\n")
print(f"{len(results)} entries")
