"""Write figure-reproduction/results.json, the repository's results-check file (tools/check_results.py):
every value our run gives for a printed table cell, Fig. 1B value, Fig. 1A pixel score or claim becomes an
entry whose expected value is the committed output, so CI catches any drift.

Usage: make_results_check.py OUTPUT_DIR OUT_JSON
"""
import json
import sys
from pathlib import Path

out_dir, out = Path(sys.argv[1]), sys.argv[2]
comp = json.load(open(out_dir / "comparison.json"))
figs = json.load(open(out_dir / "figures.json"))
claims = json.load(open(out_dir / "claims.json"))
NUM = {"rel": 1e-9, "abs": 1e-12}
results = []


def add(id_, label, file, path, value):
    e = {"id": id_, "label": label, "file": file, "path": path, "expected": value}
    if isinstance(value, float):
        e["tolerance"] = NUM
    results.append(e)


for item, block in comp["items"].items():
    for i, f in enumerate(block["fields"]):
        if f["observed"] is not None:
            add(f"{item}.{i}", f"{item}, {f['name']} (paper {f['expected']})", "comparison.json", f"items.{item}.fields.{i}.observed", f["observed"])
e = figs["figures"]["fig1a"]
for side in ("published_near_ours", "ours_near_published"):
    add(f"fig1a.{side}", f"Fig. 1A, {side.replace('_', ' ')}", "figures.json", f"figures.fig1a.{side}", e[side])
for cid, c in claims.items():
    if cid.startswith("_"):
        continue
    for i, f in enumerate(c["fields"]):
        if f.get("observed") is not None:
            add(f"{cid}.{i}", f"{cid}, {f['name']} (paper {f['expected']})", "claims.json", f"{cid}.fields.{i}.observed", f["observed"])
doc = {"paper": "PMC1523355",
       "title": "Hayward RA, Kent DM, Vijan S, Hofer TP. Multivariable risk prediction can greatly enhance the statistical power of clinical trial subgroup analysis. BMC Medical Research Methodology 6:18 (2006)",
       "about": "Our value for every printed cell of Tables 1-5, every value of Fig. 1B, the pixel scores of Fig. 1A and every claim the reproduction compares. CI reruns the whole pipeline and checks each value with tools/check_results.py. Generated by pipeline/make_results_check.py from the committed outputs.",
       "committed_paths": {"": "output/"},
       "results": results}
Path(out).write_text(json.dumps(doc, indent=1) + "\n")
print(f"{out}: {len(results)} entries", file=sys.stderr)
