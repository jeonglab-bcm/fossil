"""Write figure-reproduction/results.json, the repository's results-check file (tools/check_results.py):
every value our run gives for a published table cell, figure point or claim (comparison.json) becomes
an entry whose expected value is the committed output, so CI catches any drift of the reproduction.

  make_results_check.py COMMITTED_OUTPUT_DIR OUT_JSON
"""
import json
import sys
from pathlib import Path

committed, out = sys.argv[1:3]
comp = json.load(open(Path(committed) / "comparison.json"))
results = []
for it in comp["item_list"]:
    if "matched" in it:
        # a figure: its count of matching points (each point is checked by the reproduce workflow,
        # which compares the whole comparison.json with the committed one)
        results.append({"id": f"{it['id']}.matched", "label": f"{it['id']}, points within tolerance (of {it['of']})",
                        "file": "comparison.json", "path": f"item_list.key={it['key']}.matched",
                        "expected": it["matched"]})
        continue
    for i, f in enumerate(it["fields"]):
        e = {"id": f"{it['id']}.{i}", "label": f"{it['id']}, {f['name']} (paper {f['expected']})",
             "file": "comparison.json", "path": f"item_list.key={it['key']}.fields.{i}.observed",
             "expected": f["observed"]}
        if isinstance(f["observed"], float):
            e["tolerance"] = {"rel": 1e-6, "abs": 1e-12}
        results.append(e)
doc = {"paper": "PMC2824146",
       "title": "Marshall A, Altman DG, Royston P, Holder RL. Comparison of techniques for handling missing covariate data within prognostic modelling studies: a simulation study. BMC Medical Research Methodology 10:7 (2010)",
       "about": "Our value for every published table cell, Figure 1 bar, reference line and claim that the reproduction compares, and for Figures 2 to 8 the number of plotted points (read from the article's vector figures) within tolerance; the reproduce workflow checks every point through comparison.json. CI reruns the pipeline (replicate 1 of the MAR and MNAR studies from scratch; the rest from the committed per-replicate results in output/sim) and checks each value with tools/check_results.py. Generated by pipeline/make_results_check.py from the committed comparison.json.",
       "committed_paths": {"": "output/"},
       "results": results}
Path(out).write_text(json.dumps(doc, indent=1) + "\n")
print(f"{len(results)} entries")
