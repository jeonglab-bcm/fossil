"""Write figure-reproduction/results.json, the repository's results-check file (tools/check_results.py):
every value our run gives for a printed table cell, figure curve point, pixel score, Table 4 call and
claim becomes an entry whose expected value is the committed output, so CI catches any drift.

Usage: make_results_check.py OUTPUT_DIR OUT_JSON
"""
import json
import sys
from pathlib import Path

out_dir, out = Path(sys.argv[1]), sys.argv[2]
comp = json.load(open(out_dir / "comparison.json"))
figs = json.load(open(out_dir / "figures.json"))
t4 = json.load(open(out_dir / "table4.json"))
claims = json.load(open(out_dir / "claims.json"))
NUM = {"rel": 1e-9, "abs": 1e-12}
results = []


def add(id_, label, file, path, value):
    e = {"id": id_, "label": label, "file": file, "path": path, "expected": value}
    if isinstance(value, float):
        e["tolerance"] = NUM
    results.append(e)


for t in ("table1", "table2", "table3", "tableS1", "fig5"):
    for i, f in enumerate(comp["tables"][t]["fields"]):
        add(f"{t}.{i}", f"{t}, {f['name']} (paper {f['expected']})", "comparison.json", f"tables.{t}.fields.{i}.observed", f["observed"])
for fig, e in figs["figures"].items():
    for side in ("published_near_ours", "ours_near_published"):
        add(f"{fig}.{side}", f"{fig}, {side.replace('_', ' ')}", "figures.json", f"figures.{fig}.{side}", e[side])
    for i, f in enumerate(e["tpr_fields"]):
        add(f"{fig}.tpr{i}", f"{fig}, TPR of {f['name']} (paper {f['expected']})", "figures.json", f"figures.{fig}.tpr_fields.{i}.observed", f["observed"])
for i, f in enumerate(t4["fields"]):
    add(f"table4.{i}", f"Table 4, {f['name']} (paper {f['expected']})", "table4.json", f"fields.{i}.observed", f["observed"])
for cid, c in claims.items():
    if cid.startswith("_"):
        continue
    for i, f in enumerate(c["fields"]):
        add(f"{cid}.{i}", f"{cid}, {f['name']} (paper {f['expected']})", "claims.json", f"{cid}.fields.{i}.observed", f["observed"])
doc = {"paper": "PMC3392844",
       "title": "Liu M, Wu Y, Chen Y, Sun J, Zhao Z, Chen XW, Matheny ME, Xu H. Large-scale prediction of adverse drug reactions using chemical, biological, and phenotypic properties of drugs. J Am Med Inform Assoc 19(e1):e28-e35 (2012)",
       "about": "Our value for every printed cell of Tables 1-4 and S1, every point and pixel score of Figs 2-4, Fig. 5's counts and every claim the reproduction compares. CI reruns the whole pipeline and checks each value with tools/check_results.py. Generated by pipeline/make_results_check.py from the committed outputs.",
       "committed_paths": {"": "output/"},
       "results": results}
Path(out).write_text(json.dumps(doc, indent=1) + "\n")
print(f"{out}: {len(results)} entries", file=sys.stderr)
