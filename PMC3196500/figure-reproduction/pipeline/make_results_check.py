"""Write figure-reproduction/results.json, the repository's results-check file (tools/check_results.py):
every value our run gives for a printed table cell, a figure panel's pixel scores and a claim becomes an
entry whose expected value is the committed output, so CI catches any drift.

Usage: make_results_check.py OUTPUT_DIR OUT_JSON
"""
import json
import sys
from pathlib import Path

out_dir, out = Path(sys.argv[1]), sys.argv[2]
tabs = json.load(open(out_dir / "tables.json"))
figs = json.load(open(out_dir / "figures.json"))
claims = json.load(open(out_dir / "claims.json"))
NUM = {"rel": 1e-9, "abs": 1e-12}
results = []


def add(id_, label, file, path, value):
    e = {"id": id_, "label": label, "file": file, "path": path, "expected": value}
    if isinstance(value, float):
        e["tolerance"] = NUM
    results.append(e)


for t, block in tabs["tables"].items():
    for i, f in enumerate(block.get("fields", [])):
        add(f"{t}.{i}", f"{t}, {f['name']} (paper {f['expected']})", "tables.json", f"tables.{t}.fields.{i}.observed", f["observed"])
for fig, e in figs["figures"].items():
    for j, p in enumerate(e["panels"]):
        for side in ("published_near_ours", "ours_near_published"):
            add(f"{fig}.{j}.{side}", f"{fig} panel {j + 1}, {side.replace('_', ' ')}", "figures.json",
                f"figures.{fig}.panels.{j}.{side}", p[side])
for k, c in enumerate(claims["claims"]):
    for i, f in enumerate(c["fields"]):
        add(f"{c['id']}.{i}", f"{c['id']}, {f['name']} (paper {f['expected']})", "claims.json", f"claims.{k}.fields.{i}.observed", f["observed"])
doc = {"paper": "PMC3196500",
       "title": "Thorlund K, Imberger G, Walsh M, et al. The number of patients and events required to limit the risk of overestimation of intervention effects in meta-analysis - a simulation study. PLoS ONE 6(10):e25491 (2011)",
       "about": "Our value for every printed cell of Tables 1-4, S3 and S4, the pixel scores of every panel of Fig. 2 and Figs S1-S12, and every claim the reproduction compares. CI reruns the whole pipeline and checks each value with tools/check_results.py. Generated by pipeline/make_results_check.py from the committed outputs.",
       "committed_paths": {"": "output/"},
       "results": results}
Path(out).write_text(json.dumps(doc, indent=1) + "\n")
print(f"{out}: {len(results)} entries", file=sys.stderr)
