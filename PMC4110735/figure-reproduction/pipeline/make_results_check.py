"""Write figure-reproduction/results.json, the repository's results-check file (tools/check_results.py):
the numbers the reproduction stands on, with the committed outputs as expected values, so CI catches drift.

  make_results_check.py COMMITTED_OUTPUT_DIR OUT_JSON
"""
import json, sys
from pathlib import Path

committed, out = sys.argv[1:3]
c = Path(committed)
dream = json.load(open(c / "dream.json"))
prof = json.load(open(c / "profiles.json"))
enr = json.load(open(c / "enrich.json"))
res = []
for ds, row in dream["datasets"].items():
    for m in ("gecon", "aracne", "clr", "mrnet"):
        for k in ("aupr", "auroc", "f_max"):
            res.append({"id": f"table2.{ds}.{m}.{k}", "label": f"Table 2, {ds} {m} {k}", "file": "dream.json",
                        "path": f"datasets.{ds}.{m}.{k}", "expected": row[m][k], "tolerance": {"abs": 1e-6}})
for fig in ("fig2", "fig3", "fig7"):
    for k in ("published_near_ours", "ours_near_published"):
        res.append({"id": f"{fig}.{k}", "label": f"{fig}, {k.replace('_', ' ')}", "file": "profiles.json",
                    "path": f"{fig}.combined.{k}", "expected": prof[fig]["combined"][k], "tolerance": {"abs": 1e-4}})
for tab in ("table4", "table5"):
    for i, r in enumerate(enr[tab]):
        if r["found"] is not None:
            res.append({"id": f"{tab}.{i}", "label": f"{tab}, {r['dataset']}: {r['term']}", "file": "enrich.json",
                        "path": f"{tab}.{i}.found", "expected": r["found"]})
doc = {"paper": "PMC4110735",
       "title": "Roy S, Bhattacharyya DK, Kalita JK. Reconstruction of gene co-expression network from microarray data using local expression patterns. BMC Bioinformatics 15(Suppl 7):S10 (2014)",
       "about": "Our value for every Table 2 score, the pixel scores of Figs 2, 3 and 7, and every Table 4 and 5 term we test. CI reruns the pipeline and checks each value with tools/check_results.py. Generated by pipeline/make_results_check.py from the committed outputs.",
       "committed_paths": {"": "output/"},
       "results": res}
Path(out).write_text(json.dumps(doc, indent=2) + "\n")
print(f"{len(res)} entries")
