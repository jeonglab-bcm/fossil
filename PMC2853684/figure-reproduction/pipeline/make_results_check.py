"""Write figure-reproduction/results.json, the repository's results-check file (tools/check_results.py):
every value our run gives for a number the paper prints or draws (comparison.json) becomes an entry
whose expected value is the committed output, so CI catches any drift of the reproduction.

  make_results_check.py COMMITTED_OUTPUT_DIR OUT_JSON
"""
import json
import sys
from pathlib import Path

committed, out = sys.argv[1:3]
comp = json.load(open(Path(committed) / "comparison.json"))
results = []
for it in comp["item_list"]:
    key = it["key"]
    src = next(k for k in comp if k != "item_list" and k.replace(".", "") == key)
    for i, f in enumerate(it["fields"]):
        results.append({"id": f"{src}.{i}", "label": f"{src}, {f['name']} (paper {f['expected']})",
                        "file": "comparison.json", "path": f"item_list.key={key}.fields.{i}.observed",
                        "expected": f["observed"]})
doc = {"paper": "PMC2853684",
       "title": "Navlakha S, Kingsford C. The power of protein interaction networks for associating genes with diseases. Bioinformatics 26(8):1057-1063 (2010)",
       "about": "Our value for every number the paper prints or draws that the reproduction compares (figure values read from the vector PDFs). CI reruns the whole pipeline from the downloaded inputs and checks each value with tools/check_results.py. Generated by pipeline/make_results_check.py from the committed comparison.json.",
       "committed_paths": {"": "output/"},
       "results": results}
Path(out).write_text(json.dumps(doc, indent=2) + "\n")
print(f"{len(results)} entries")
