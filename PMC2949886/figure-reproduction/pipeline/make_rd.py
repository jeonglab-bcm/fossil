"""Write package/man/*.Rd from the roxygen comments in package/R/*.R.

A small stand-in for roxygen2's Rd roclet (roxygen2 needs xml2, which needs libxml2 headers that the
cluster lacks). It understands the tags the package uses: a title line, description paragraphs,
@param, @return, @examples, @name, @rdname. Usage: python make_rd.py <package dir>
"""
import re
import sys
from pathlib import Path


def blocks(text):
    lines = text.splitlines()
    i = 0
    while i < len(lines):
        if lines[i].startswith("#'"):
            doc = []
            while i < len(lines) and lines[i].startswith("#'"):
                doc.append(lines[i][2:].removeprefix(" "))
                i += 1
            sig = []
            if i < len(lines) and re.match(r"^[A-Za-z_.][A-Za-z0-9_.]* <- function", lines[i]):
                depth = 0
                while i < len(lines):
                    sig.append(lines[i])
                    depth += lines[i].count("(") - lines[i].count(")")
                    if depth <= 0 and "{" in lines[i]:
                        break
                    i += 1
            yield doc, "\n".join(sig)
        i += 1


def parse(doc):
    out = {"title": None, "desc": [], "params": [], "return": None, "examples": [], "name": None, "rdname": None}
    cur = None
    para = []
    for ln in doc:
        m = re.match(r"@(\w+)\s*(.*)", ln)
        if m:
            tag, rest = m.groups()
            if tag == "param":
                nm, _, d = rest.partition(" ")
                out["params"].append([nm, d])
                cur = ("param", len(out["params"]) - 1)
            elif tag == "return":
                out["return"] = rest
                cur = ("return",)
            elif tag == "examples":
                cur = ("examples",)
            elif tag in ("name", "rdname"):
                out[tag] = rest.strip()
                cur = None
            continue
        if cur is None:
            if out["title"] is None:
                if ln.strip():
                    out["title"] = ln.strip()
                continue
            para.append(ln)
        elif cur[0] == "param":
            out["params"][cur[1]][1] += " " + ln.strip()
        elif cur[0] == "return":
            out["return"] += " " + ln.strip()
        elif cur[0] == "examples":
            out["examples"].append(ln)
    out["desc"] = "\n".join(para).strip()
    return out


def usage(sig):
    m = re.match(r"^([A-Za-z_.][A-Za-z0-9_.]*) <- function\((.*)\)\s*\{", sig, re.S)
    name, args = m.groups()
    args = re.sub(r"\s+", " ", args).strip()
    return name, f"{name}({args})"


def esc(s):
    return s.replace("%", "\\%")


def main(pkg):
    topics = {}
    for f in sorted((Path(pkg) / "R").glob("*.R")):
        for doc, sig in blocks(f.read_text()):
            p = parse(doc)
            key = p["rdname"] or p["name"]
            fn = None
            if sig:
                fn, us = usage(sig)
                key = key or fn
            t = topics.setdefault(key, {"title": None, "desc": "", "params": [], "return": None,
                                        "examples": [], "aliases": [], "usage": []})
            for k in ("title", "return"):
                t[k] = t[k] or p[k]
            t["desc"] = t["desc"] or p["desc"]
            t["examples"] += p["examples"]
            for nm, d in p["params"]:
                if nm not in [q[0] for q in t["params"]]:
                    t["params"].append([nm, d.strip()])
            if p["name"]:
                t["aliases"].append(p["name"])
            if fn:
                t["aliases"].append(fn)
                t["usage"].append(us)
    man = Path(pkg) / "man"
    man.mkdir(exist_ok=True)
    for key, t in topics.items():
        rd = [f"% Generated by figure-reproduction/pipeline/make_rd.py from the comments in R/: do not edit",
              f"\\name{{{key}}}"]
        rd += [f"\\alias{{{a}}}" for a in dict.fromkeys(t["aliases"])]
        rd.append(f"\\title{{{esc(t['title'])}}}")
        rd.append("\\usage{\n" + "\n\n".join(t["usage"]) + "\n}")
        if t["params"]:
            rd.append("\\arguments{\n" + "\n".join(
                f"\\item{{{nm}}}{{{esc(d)}}}" for nm, d in t["params"]) + "\n}")
        if t["return"]:
            rd.append(f"\\value{{\n{esc(t['return'])}\n}}")
        rd.append(f"\\description{{\n{esc(t['desc'] or t['title'])}\n}}")
        if t["examples"]:
            rd.append("\\examples{\n" + "\n".join(t["examples"]) + "\n}")
        (man / f"{key}.Rd").write_text("\n".join(rd) + "\n")
    print(len(topics), "Rd files")


if __name__ == "__main__":
    main(sys.argv[1])
