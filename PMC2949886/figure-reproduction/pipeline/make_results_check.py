"""Write figure-reproduction/results.json, the repository's results-check file (tools/check_results.py):
the two-way pixel score of every scored panel and the largest difference from the published values in
data units, from the committed comparison.json, so CI catches any drift of the reproduction.

  make_results_check.py COMMITTED_OUTPUT_DIR OUT_JSON
"""
import json
import sys
from pathlib import Path

committed, out = sys.argv[1:3]
comp = json.load(open(Path(committed) / "comparison.json"))
results = []
for fig, f in comp["figures"].items():
    for panel, p in f["panels"].items():
        base = f"figures.{fig}.panels.{panel}"
        results.append({"id": f"{fig}.{panel}.score", "label": f"{fig}, {panel}: smaller two-way share within 2 px",
                        "file": "comparison.json", "path": f"{base}.score", "expected": p["score"],
                        "tolerance": {"abs": 0.002}})
        if p.get("values", {}).get("max_abs") is not None:
            results.append({"id": f"{fig}.{panel}.max_abs", "label": f"{fig}, {panel}: largest difference from the published values",
                            "file": "comparison.json", "path": f"{base}.values.max_abs",
                            "expected": round(p["values"]["max_abs"], 6), "tolerance": {"abs": 1e-4}})
doc = {"paper": "PMC2949886",
       "title": "van Iterson M, Boer JM, Menezes RX. Filtering, FDR and power. BMC Bioinformatics 11:450 (2010)",
       "about": "For every scored panel: the smaller of the two shares of ink within 2 px (ours against the published "
                "vector figure), and, where the published values can be read at the same x, the largest difference in "
                "data units. CI reruns the pipeline (data sets 1-50 from scratch, the rest from the committed chunk "
                "sums in output/sim) and checks each value with tools/check_results.py. Generated by "
                "pipeline/make_results_check.py from the committed comparison.json.",
       "committed_paths": {"": "output/"},
       "results": results}
Path(out).write_text(json.dumps(doc, indent=2) + "\n")
print(f"{len(results)} entries")
