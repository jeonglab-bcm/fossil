"""Summarize the audit: per-URL categories, per-paper status, and tables for the README.

Reads papers.csv, urls.csv, url_status.csv, wayback.csv, accession_status.csv, accessions.csv,
supplement_status.csv and install_results.csv (whichever exist). Writes:
  url_audit.csv     one row per paper x URL with category, reason, host group, and Wayback capture
  paper_audit.csv   one row per paper with counts and an overall status
  summary.md        the tables quoted in README.md
"""
import csv
import re
from collections import Counter, defaultdict
from pathlib import Path
from urllib.parse import urlsplit

from classify import CATEGORIES, catch_all_finals, classify

GROUPS = [  # (group, host regex), first match wins
    ("GitHub", r"(^|\.)github\.(com|io)$|githubusercontent\.com$"),
    ("SourceForge", r"(^|\.)(sourceforge|sf)\.net$"),
    ("Google Code", r"^code\.google\.com$|\.googlecode\.com$"),
    ("Bitbucket / GitLab", r"(^|\.)(bitbucket\.org|gitlab\.com)$"),
    ("Bioconductor / CRAN", r"(^|\.)(bioconductor\.org|r-project\.org)$"),
    ("NCBI / NLM / NIH", r"(^|\.)(nih\.gov)$"),
    ("EBI / EMBL / SIB", r"(^|\.)(ebi\.ac\.uk|embl\.de|embl\.org|expasy\.org|uniprot\.org|ensembl\.org)$"),
    ("Journal / publisher", r"(^|\.)(biomedcentral\.com|oxfordjournals\.org|oup\.com|plos\.org|ploscompbiol\.org|"
                            r"springer\.com|springeropen\.com|nature\.com|sciencedirect\.com|elsevier\.com|wiley\.com|"
                            r"bmj\.com|jamia\.org|doi\.org|pubmedcentral\.nih\.gov|la-press\.com|libertasacademica\.com)$"),
    ("University / research institute", r"\.(edu|edu\.[a-z]{2}|ac\.[a-z]{2})$|(^|\.)(uni-[a-z-]+|univ[a-z-]*)\.|"
                                        r"\.(mpg\.de|cnrs\.fr|inria\.fr|riken\.jp|csiro\.au|dtu\.dk|ethz\.ch|epfl\.ch|"
                                        r"ku\.dk|tum\.de|kaist\.ac\.kr)$|(^|\.)(uni|univ)[a-z-]*\.[a-z]+$"),
    ("Other .gov", r"\.gov$"),
]
GROUP_NAMES = [g for g, _ in GROUPS] + ["Other"]


def host_group(host):
    for name, rx in GROUPS:
        if re.search(rx, host):
            return name
    return "Other"


def read(path, comment=False):
    if not Path(path).exists():
        return []
    with open(path) as f:
        return list(csv.DictReader(l for l in f if not (comment and l.startswith("#"))))


def pct(n, d):
    return f"{100 * n / d:.1f}%" if d else "–"


def table(header, rows):
    out = ["| " + " | ".join(header) + " |", "| " + " | ".join("---" for _ in header) + " |"]
    out += ["| " + " | ".join(str(c) for c in r) + " |" for r in rows]
    return "\n".join(out)


def main():
    papers = read("papers.csv", comment=True)
    for p in papers:
        p["pmcid"] = "PMC" + p["pmcid"].removeprefix("PMC")
    year = {p["pmcid"]: int(p["year"]) for p in papers}
    status = {r["url"]: r for r in read("url_status.csv")}
    ca = catch_all_finals(list(status.values()))
    wb = {r["url"]: r for r in read("wayback.csv")}
    urls = read("urls.csv")
    rows = []
    for u in urls:
        st = status.get(u["url"])
        cat, why = classify(st, ca) if st else ("unchecked", "")
        w = wb.get(u["url"], {})
        rows.append({"pmcid": u["pmcid"], "year": year[u["pmcid"]], "url": u["url"], "host": u["host"],
                     "group": host_group(u["host"]), "availability_section": u["availability_section"],
                     "category": cat, "reason": why,
                     "wayback": "" if cat in ("alive", "moved") else w.get("archived", ""),
                     "wayback_year": w.get("snapshot_timestamp", "")[:4]})
    with open("url_audit.csv", "w", newline="") as f:
        wr = csv.DictWriter(f, list(rows[0]))
        wr.writeheader()
        wr.writerows(rows)

    md = ["# Audit summary (generated by summarize.py)", ""]
    n_p = len(papers)
    with_url = {r["pmcid"] for r in rows}
    md.append(f"Papers: {n_p}. With at least one body-text URL: {len(with_url)} ({pct(len(with_url), n_p)}). "
              f"Paper x URL rows: {len(rows)}; distinct URLs: {len(status)}; checked: "
              f"{sum(r['category'] != 'unchecked' for r in rows)} rows.")
    md.append("")

    # 1. URL categories, distinct URLs and paper x URL rows
    uc = Counter(classify(s, ca)[0] for s in status.values())
    rc = Counter(r["category"] for r in rows)
    md += ["## URL status", "", table(["Category", "Distinct URLs", "Share", "Paper x URL rows", "Share"],
                                      [(c, uc[c], pct(uc[c], sum(uc.values())), rc[c], pct(rc[c], len(rows)))
                                       for c in CATEGORIES]), ""]
    reasons = Counter((r["category"], r["reason"]) for r in rows if r["category"] not in ("alive",))
    md += ["Reasons (paper x URL rows):", "", table(["Category", "Reason", "Rows"],
                                                   [(c, w, n) for (c, w), n in reasons.most_common(25)]), ""]

    # 2. by publication year
    by_year = defaultdict(Counter)
    for r in rows:
        by_year[r["year"]][r["category"]] += 1
    md += ["## By publication year (paper x URL rows)", "",
           table(["Year", "Rows"] + CATEGORIES + ["alive or moved"],
                 [(y, sum(c.values()), *[pct(c[k], sum(c.values())) for k in CATEGORIES],
                   pct(c["alive"] + c["moved"], sum(c.values()))) for y, c in sorted(by_year.items())]), ""]

    # 3. by host group
    by_group = defaultdict(Counter)
    for r in rows:
        by_group[r["group"]][r["category"]] += 1
    md += ["## By host group (paper x URL rows)", "",
           table(["Host group", "Rows"] + CATEGORIES,
                 [(g, sum(c.values()), *[pct(c[k], sum(c.values())) for k in CATEGORIES])
                  for g, c in sorted(by_group.items(), key=lambda kv: -sum(kv[1].values()))]), ""]

    # 4. own-resource links (abstract or availability-type sections), per paper
    own = defaultdict(list)
    for r in rows:
        if r["availability_section"] == "True":
            own[r["pmcid"]].append(r["category"])
    pc = Counter()
    for cats in own.values():
        live = sum(c in ("alive", "moved") for c in cats)
        dead = sum(c in ("gone", "unreachable") for c in cats)
        pc["all alive" if live == len(cats) else "none alive, at least one dead" if live == 0 and dead else
           "some alive" if live else "none alive, rest indeterminate/untestable"] += 1
    md += ["## Papers by status of their own-resource links (abstract or availability-type sections)", "",
           table(["Status", "Papers", "Share"], [(k, v, pct(v, len(own))) for k, v in pc.most_common()]), ""]

    # 5. Wayback
    dead = [r for r in rows if r["category"] in ("gone", "unreachable", "indeterminate", "untestable")]
    looked = [r for r in dead if r["wayback"] != ""]
    arch = [r for r in looked if r["wayback"] == "True"]
    near = [r for r in arch if r["wayback_year"] and abs(int(r["wayback_year"]) - r["year"]) <= 2]
    md += ["## Wayback Machine captures for links that are not alive", "",
           f"Looked up: {len(looked)} of {len(dead)} rows. Some capture: {len(arch)} ({pct(len(arch), len(looked))}). "
           f"Closest capture within 2 years of publication: {len(near)} ({pct(len(near), len(looked))}).", ""]
    wg = defaultdict(Counter)
    for r in looked:
        wg[r["category"]]["n"] += 1
        wg[r["category"]]["arch"] += r["wayback"] == "True"
    md += [table(["Category", "Looked up", "Archived"], [(k, c["n"], pct(c["arch"], c["n"])) for k, c in wg.items()]), ""]

    # 6. accessions
    acc_st = {(r["type"], r["accession"]): r for r in read("accession_status.csv")}
    if acc_st:
        ac = defaultdict(Counter)
        for (t, a), r in acc_st.items():
            ac[t][r["status"]] += 1
        sts = ["live", "obsolete", "not_found", "error"]
        md += ["## Repository accessions (distinct)", "",
               table(["Type", "Distinct"] + sts, [(t, sum(c.values()), *[c[s] for s in sts])
                                                  for t, c in sorted(ac.items(), key=lambda kv: -sum(kv[1].values()))]),
               ""]
        acc_rows = read("accessions.csv")
        papers_acc = {r["pmcid"] for r in acc_rows}
        bad = {r["pmcid"] for r in acc_rows if acc_st.get((r["type"], r["accession"]), {}).get("status") in
               ("obsolete", "not_found") and r["type"] != "PDB"}
        md += [f"Papers citing at least one accession: {len(papers_acc)} ({pct(len(papers_acc), n_p)}). "
               f"Papers with a non-PDB accession that no longer resolves or is obsolete: {len(bad)}.", ""]

    # 7. supplements
    sup = read("supplement_status.csv")
    if sup:
        sc = Counter(r["status"] for r in sup)
        sp = {r["pmcid"] for r in sup}
        code_p = {r["pmcid"] for r in sup if r["has_code"] == "True"}
        build_p = {r["pmcid"] for r in sup if r["build_files"]}
        md += ["## Supplementary files in the PMC dataset", "",
               f"Papers with supplementary files: {len(sp)} ({pct(len(sp), n_p)}); files: {len(sup)}.",
               "", table(["Status", "Files", "Share"], [(k, v, pct(v, len(sup))) for k, v in sc.most_common()]), "",
               f"Papers whose supplements contain source code: {len(code_p)} ({pct(len(code_p), n_p)}); "
               f"with build or package files (Makefile, DESCRIPTION, setup.py, README...): {len(build_p)}.", ""]

    # 8. install sample
    inst = read("install_results.csv")
    if inst:
        smp = {r["pmcid"]: r for r in read("install_sample.csv", comment=True)}
        ic = Counter(r["kind"] if r["installed"] == "n/a" else ("installed" if r["installed"] == "yes" else
                     "source unavailable" if r["obtained"] == "no" else "obtained, install failed") for r in inst)
        md += ["## Install test (stratified random sample)", "",
               table(["Outcome", "Papers", "Share"], [(k, v, pct(v, len(inst))) for k, v in ic.most_common()]), ""]
        band = defaultdict(Counter)
        for r in inst:
            y = year[r["pmcid"]]
            b = "2004-2007" if y <= 2007 else "2008-2011" if y <= 2011 else "2012-2015"
            band[b]["n"] += 1
            band[b]["released"] += r["kind"] not in ("none", "request", "webserver") or r["via"] == "alternate"
            band[b]["obtained"] += r["obtained"] == "yes"
            band[b]["installed"] += r["installed"] == "yes"
        md += [table(["Years", "Papers", "Released downloadable software", "Source obtained today", "Installs today"],
                     [(b, c["n"], c["released"], c["obtained"], c["installed"]) for b, c in sorted(band.items())]), ""]
        fails = Counter((r["build_system"], r["failure"]) for r in inst if r["installed"] == "no")
        md += [table(["Build system", "Failure", "Papers"], [(b or "–", f, n) for (b, f), n in fails.most_common()]), ""]
        _ = smp
    md += paper_tiers(papers, rows)
    Path("summary.md").write_text("\n".join(md) + "\n")
    print("\n".join(md))


CODE_GROUPS = {"GitHub", "SourceForge", "Google Code", "Bitbucket / GitLab", "Bioconductor / CRAN"}
TIERS = [
    ("A", "code in the PMC supplement"),
    ("B", "reachable link to a code host or package repository"),
    ("C", "reachable own-resource link (lab page, web service)"),
    ("D", "own-resource links dead, Wayback capture exists"),
    ("E", "own-resource links dead, no Wayback capture"),
    ("F", "own-resource links can't be told (blocked or untestable)"),
    ("G", "no own-resource link and no code supplement"),
]


def paper_tiers(papers, rows):
    """Per-paper readiness for reproduction; writes paper_audit.csv, returns summary lines."""
    sup = read("supplement_status.csv")
    code = {r["pmcid"] for r in sup if r["has_code"] == "True"}
    nsup = Counter(r["pmcid"] for r in sup)
    acc = {(r["type"], r["accession"]): r["status"] for r in read("accession_status.csv")}
    acc_p = defaultdict(Counter)
    for r in read("accessions.csv"):
        acc_p[r["pmcid"]][acc.get((r["type"], r["accession"]), "unchecked")] += 1
    by_p = defaultdict(list)
    for r in rows:
        by_p[r["pmcid"]].append(r)
    out = []
    for p in papers:
        rs = by_p.get(p["pmcid"], [])
        own = [r for r in rs if r["availability_section"] == "True"]
        c = Counter(r["category"] for r in rs)
        oc = Counter(r["category"] for r in own)
        reach = lambda r: r["category"] in ("alive", "moved")  # noqa: E731
        dead = [r for r in own if r["category"] in ("gone", "unreachable")]
        if p["pmcid"] in code:
            tier = "A"
        elif any(reach(r) and r["group"] in CODE_GROUPS for r in rs):
            tier = "B"
        elif any(reach(r) for r in own):
            tier = "C"
        elif dead and any(r["wayback"] == "True" for r in dead):
            tier = "D"
        elif dead:
            tier = "E"
        elif own:
            tier = "F"
        else:
            tier = "G"
        out.append({"pmcid": p["pmcid"], "pmid": p["pmid"], "year": p["year"], "journal": p["journal"],
                    "title": p["title"], "tier": tier, "urls": len(rs),
                    "reachable": c["alive"] + c["moved"], "gone": c["gone"], "unreachable": c["unreachable"],
                    "cant_tell": c["indeterminate"] + c["untestable"], "own_urls": len(own),
                    "own_reachable": oc["alive"] + oc["moved"], "own_dead": len(dead),
                    "code_host_links_reachable": sum(reach(r) and r["group"] in CODE_GROUPS for r in rs),
                    "supplementary_files": nsup[p["pmcid"]], "supplement_has_code": p["pmcid"] in code,
                    "accessions": sum(acc_p[p["pmcid"]].values()),
                    "accessions_not_resolving": acc_p[p["pmcid"]]["not_found"] + acc_p[p["pmcid"]]["obsolete"]})
    with open("paper_audit.csv", "w", newline="") as f:
        w = csv.DictWriter(f, list(out[0]))
        w.writeheader()
        w.writerows(out)
    tc = Counter(r["tier"] for r in out)
    by_band = defaultdict(Counter)
    for r in out:
        y = int(r["year"])
        by_band["2004-2007" if y <= 2007 else "2008-2011" if y <= 2011 else "2012-2015"][r["tier"]] += 1
    bands = sorted(by_band)
    return ["## Papers by reproduction readiness (first matching tier)", "",
            table(["Tier", "Meaning", "Papers", "Share"] + bands,
                  [(t, m, tc[t], pct(tc[t], len(out)), *[by_band[b][t] for b in bands]) for t, m in TIERS]), ""]


if __name__ == "__main__":
    main()
