"""Write figure-reproduction/results.json, the repository's results-check file (tools/check_results.py):
every value our run gives for a printed number (analysis.json items), the Figure 3 pixel scores
(figures.json) and the port check become entries whose expected value is the committed output, so
CI catches any drift of the reproduction.

  make_results_check.py COMMITTED_OUTPUT_DIR OUT_JSON
"""
import json
import sys
from pathlib import Path

committed, out = sys.argv[1:3]
an = json.load(open(Path(committed) / "analysis.json"))
fg = json.load(open(Path(committed) / "figures.json"))
results = []
for key, fields in an["items"].items():
    for i, f in enumerate(fields):
        e = {"id": f"{key}.{i}", "label": f"{key}, {f['name']} (paper {f['expected']})",
             "file": "analysis.json", "path": f"item_list.key={key.replace('.', '_')}.fields.{i}.observed",
             "expected": f["observed"]}
        if isinstance(f["observed"], float):
            e["tolerance"] = {"rel": 1e-9}
        results.append(e)
for p in "abc":
    for k in ("published_near_ours", "ours_near_published"):
        results.append({"id": f"fig3.{p}.{k}", "label": f"Fig. 3{p.upper()}, {k.replace('_', ' ')} within 2 px",
                        "file": "figures.json", "path": f"fig3.{p}.{k}", "expected": fg["fig3"][p][k], "tolerance": {"abs": 1e-9}})
for i, pc in enumerate(an["port_check"]):
    results.append({"id": f"port.{i}", "label": f"Port against Weka 3.4.3, {pc['label']}", "file": "analysis.json",
                    "path": f"port_check.{i}.passed", "expected": True})
doc = {"paper": "PMC1274252",
       "title": "Adie EA, Adams RR, Evans KL, Porteous DJ, Pickard BS. Speeding disease gene discovery by sequence based candidate prioritization. BMC Bioinformatics 6:55 (2005)",
       "about": "Our value for every printed number the reproduction compares, the Figure 3 pixel scores and the port check. CI reruns the pipeline and checks each value with tools/check_results.py. Generated by pipeline/make_results_check.py from the committed analysis.json and figures.json.",
       "committed_paths": {"": "output/"},
       "results": results}
Path(out).write_text(json.dumps(doc, indent=2) + "\n")
print(f"{len(results)} entries")
