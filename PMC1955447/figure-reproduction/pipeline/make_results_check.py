"""Write figure-reproduction/results.json, the repository's results-check file (tools/check_results.py):
every value our run gives for a printed table cell or a claim becomes an entry whose expected value is the
committed output, so CI catches any drift.

Usage: make_results_check.py OUTPUT_DIR OUT_JSON
"""
import json
import sys
from pathlib import Path

out_dir, out = Path(sys.argv[1]), sys.argv[2]
comp = json.load(open(out_dir / "comparison.json"))
claims = json.load(open(out_dir / "claims.json"))
NUM = {"rel": 1e-9, "abs": 1e-12}
results = []


def add(id_, label, file, path, value):
    e = {"id": id_, "label": label, "file": file, "path": path, "expected": value}
    if isinstance(value, float):
        e["tolerance"] = NUM
    results.append(e)


for t, block in comp["tables"].items():
    for i, f in enumerate(block["fields"]):
        add(f"{t}.{i}", f"{t}, {f['name']} (paper {f['expected']})", "comparison.json", f"tables.{t}.fields.{i}.observed", f["observed"])
for cid, c in claims.items():
    if cid.startswith("_"):
        continue
    for i, f in enumerate(c["fields"]):
        add(f"{cid}.{i}", f"{cid}, {f['name']} (paper {f['expected']})", "claims.json", f"{cid}.fields.{i}.observed", f["observed"])
add("crosscheck.passed", "mlagq's likelihood equals a dense-grid integral, and its maxima are the exact likelihood's", "crosscheck.json", "passed", True)
doc = {"paper": "PMC1955447",
       "title": "Moineddin R, Matheson FI, Glazier RH. A simulation study of sample size for multilevel logistic regression models. BMC Medical Research Methodology 7:34 (2007)",
       "about": "Our value for every printed cell of Tables 1-5 and every claim the reproduction compares. CI reruns the pipeline and checks each value with tools/check_results.py. Generated by pipeline/make_results_check.py from the committed outputs.",
       "committed_paths": {"": "output/"},
       "results": results}
Path(out).write_text(json.dumps(doc, indent=1, ensure_ascii=False) + "\n")
print(f"{out}: {len(results)} entries", file=sys.stderr)
