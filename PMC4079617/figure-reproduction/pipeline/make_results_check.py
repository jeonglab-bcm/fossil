"""Write figure-reproduction/results.json, the repository's results-check file (tools/check_results.py): every
value our run gives for a printed table cell, a claim or a figure score becomes an entry whose expected value is
the committed output, so CI catches any drift.

Usage: make_results_check.py OUTPUT_DIR OUT_JSON
"""
import json
import sys
from pathlib import Path

out_dir, out = Path(sys.argv[1]), sys.argv[2]
comp = json.load(open(out_dir / "comparison.json"))
claims = json.load(open(out_dir / "claims.json"))
fig = json.load(open(out_dir / "figure.json"))
NUM = {"rel": 1e-9, "abs": 1e-12}
results = []


def add(id_, label, file, path, value):
    e = {"id": id_, "label": label, "file": file, "path": path, "expected": value}
    if isinstance(value, float):
        e["tolerance"] = NUM
    results.append(e)


for t, block in comp["tables"].items():
    for i, f in enumerate(block["fields"]):
        add(f"{t}.{i}", f"{block['label']}, {f['name']} (paper {f['expected']})", "comparison.json", f"tables.{t}.fields.{i}.observed", f["observed"])
for cid, c in claims.items():
    if cid.startswith("_"):
        continue
    for i, f in enumerate(c["fields"]):
        add(f"{cid}.{i}", f"{cid}, {f['name']} (paper {f['expected']})", "claims.json", f"{cid}.fields.{i}.observed", f["observed"])
for p, v in fig["panels"].items():
    for k in ("published_near_ours", "ours_near_published"):
        add(f"fig1.{p}.{k}", f"Fig. 1{p.upper()}, {k.replace('_', ' ')} within 2 px", "figure.json", f"panels.{p}.{k}", v[k])
add("fig1.consistency", "Fig. 1 vertices within 1 point of Table 1", "figure.json", "consistency.within_1_point", fig["consistency"]["within_1_point"])
add("crosscheck.passed", "robustrr's fits equal statsmodels' and an independent maximizer's", "crosscheck.json", "passed", True)
doc = {"paper": "PMC4079617",
       "title": "Chen W, Shi J, Qian L, Azen SP. Comparison of robustness to outliers between robust poisson models and log-binomial models when estimating relative risks for common binary outcomes: a simulation study. BMC Medical Research Methodology 14:82 (2014)",
       "about": "Our value for every printed cell of Tables 1-3 and A1-A3, every claim and every Fig. 1 score the reproduction compares. CI reruns the whole pipeline and checks each value with tools/check_results.py. Generated by pipeline/make_results_check.py from the committed outputs.",
       "committed_paths": {"": "output/"},
       "results": results}
Path(out).write_text(json.dumps(doc, indent=1) + "\n")
print(f"{out}: {len(results)} entries", file=sys.stderr)
