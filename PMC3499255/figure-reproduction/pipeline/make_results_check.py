"""Write figure-reproduction/results.json, the CI results-check file.

It lists, for every reproduced number, where the pipeline writes it (a committed
output file and a path into it), the value expected, and how far a rerun may
stray. `tools/check_results.py` (in results-check.yml) compares these against the
committed outputs; a deterministic, fixed-seed rerun must reproduce them.

    make_results_check.py COMMITTED_OUTPUT_DIR OUT
"""

from __future__ import annotations

import argparse
import json
import os


def jpath(obj, path):
    cur = obj
    for key in path.split("."):
        cur = cur[int(key)] if isinstance(cur, list) else cur[key]
    return cur


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("committed")
    ap.add_argument("out")
    args = ap.parse_args()

    def load(name):
        return json.load(open(os.path.join(args.committed, name)))

    y07, y01, tst, ser = (load("y2007.json"), load("y2001.json"),
                          load("test.json"), load("series.json"))

    results = []

    def add(iid, label, file, path, obj, tol):
        results.append({"id": iid, "label": label, "file": file, "path": path,
                        "expected": round(float(jpath(obj, path)), 6),
                        "tolerance": {"abs": tol}})

    # Real-data posteriors are deterministic (fixed seed): tight tolerance.
    for tag, obj, fname in [("2007", y07, "y2007.json"), ("2001", y01, "y2001.json")]:
        add(f"{tag}_latency_median", f"{tag} mean latency median", fname, "mean_latency.median", obj, 1e-6)
        add(f"{tag}_latency_lo", f"{tag} mean latency 95% lo", fname, "mean_latency.lo", obj, 1e-6)
        add(f"{tag}_latency_hi", f"{tag} mean latency 95% hi", fname, "mean_latency.hi", obj, 1e-6)
        add(f"{tag}_distance_median", f"{tag} mean distance median", fname, "mean_distance.median", obj, 1e-6)
        add(f"{tag}_distance_lo", f"{tag} mean distance 95% lo", fname, "mean_distance.lo", obj, 1e-6)
        add(f"{tag}_distance_hi", f"{tag} mean distance 95% hi", fname, "mean_distance.hi", obj, 1e-6)
        add(f"{tag}_best_tree_prob", f"{tag} most-likely tree probability", fname, "best_tree_prob", obj, 1e-6)

    # Fig. 2 (simulated) and the series are only rerun with --full; when present in a
    # run they must match the committed values exactly (deterministic seeds).
    add("test_latency_median", "Fig. 2 mean latency median", "test.json", "mean_latency.median", tst, 1e-6)
    add("test_distance_median", "Fig. 2 mean distance median", "test.json", "mean_distance.median", tst, 1e-6)
    for s in ("test", "y2007", "y2001"):
        add(f"series_{s}_frac", f"Table 1 fraction correct, {s}", "series.json",
            f"{s}.frac_correct_mean", ser, 1e-6)
        add(f"series_{s}_post", f"Table 1 mean post. prob., {s}", "series.json",
            f"{s}.mean_post_true_mean", ser, 1e-6)

    out = {
        "paper": "PMC3499255",
        "title": ("Morelli MJ, Thebaud G, Chadoeuf J, King DP, Haydon DT, Soubeyrand S. "
                  "A Bayesian inference framework to reconstruct transmission trees using "
                  "epidemiological and genetic data. PLoS Comput Biol 8(11):e1002768 (2012)"),
        "about": ("Our value for every posterior summary the reproduction stands on. CI reruns the "
                  "2007 and 2001 analyses from scratch (fixed seed) and reads the simulated Fig. 2 "
                  "and the simulation series from the committed outputs, then checks each value with "
                  "tools/check_results.py. Generated by pipeline/make_results_check.py."),
        "committed_paths": {"": "output/"},
        "results": results,
    }
    with open(args.out, "w") as fh:
        json.dump(out, fh, indent=2)
    print(f"wrote {args.out}: {len(results)} tracked values")


if __name__ == "__main__":
    main()
