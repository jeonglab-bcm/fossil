"""Write figure-reproduction/results.json, the repository's results-check file (tools/check_results.py):
every value our run gives for a printed table cell, figure bar, pixel score, case-study value or claim
becomes an entry whose expected value is the committed output, so CI catches any drift.

Usage: make_results_check.py OUTPUT_DIR OUT_JSON
"""
import json
import sys
from pathlib import Path

out_dir, out = Path(sys.argv[1]), sys.argv[2]
comp = json.load(open(out_dir / "comparison.json"))
figs = json.load(open(out_dir / "figures.json"))
t5 = json.load(open(out_dir / "table5.json"))
claims = json.load(open(out_dir / "claims.json"))
NUM = {"rel": 1e-9, "abs": 1e-12}
results = []


def add(id_, label, file, path, value):
    e = {"id": id_, "label": label, "file": file, "path": path, "expected": value}
    if isinstance(value, float):
        e["tolerance"] = NUM
    results.append(e)


for t, block in comp["tables"].items():
    for i, f in enumerate(block["fields"]):
        if f["observed"] is not None:
            add(f"{t}.{i}", f"{t}, {f['name']} (paper {f['expected']})", "comparison.json", f"tables.{t}.fields.{i}.observed", f["observed"])
for fig, block in comp["figures"].items():
    for i, f in enumerate(block["fields"]):
        add(f"{fig}.bar{i}", f"{fig}, {f['name']} (paper {f['expected']})", "comparison.json", f"figures.{fig}.fields.{i}.observed", f["observed"])
for fig, e in figs["figures"].items():
    for side in ("published_near_ours", "ours_near_published"):
        add(f"{fig}.{side}", f"{fig}, {side.replace('_', ' ')}", "figures.json", f"figures.{fig}.{side}", e[side])
for part in ("point", "ci"):
    for i, f in enumerate(t5[part]["fields"]):
        add(f"table5.{part}{i}", f"Table 5, {f['name']} (paper {f['expected']})", "table5.json", f"{part}.fields.{i}.observed", f["observed"])
for cid, c in claims.items():
    if cid.startswith("_"):
        continue
    for i, f in enumerate(c["fields"]):
        if f.get("observed") is not None:
            add(f"{cid}.{i}", f"{cid}, {f['name']} (paper {f['expected']})", "claims.json", f"{cid}.fields.{i}.observed", f["observed"])
doc = {"paper": "PMC3022898",
       "title": "Reichmann WM, Gagnon D, Horsburgh CR, Losina E. Evaluation of exposure-specific risks from two independent samples: a simulation study. BMC Medical Research Methodology 11:1 (2011)",
       "about": "Our value for every printed cell of Tables 2-4 and S1-S7, every bar of Figs 1-4, the figures' pixel scores, Table 5 and every claim the reproduction compares. CI reruns the whole pipeline and checks each value with tools/check_results.py. Generated by pipeline/make_results_check.py from the committed outputs.",
       "committed_paths": {"": "output/"},
       "results": results}
Path(out).write_text(json.dumps(doc, indent=1) + "\n")
print(f"{out}: {len(results)} entries", file=sys.stderr)
