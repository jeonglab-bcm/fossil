"""Write figure-reproduction/results.json, the repository's results-check file (tools/check_results.py):
every value our run gives for a published number (comparison.json) becomes an entry whose expected
value is the committed output, so CI catches any drift of the reproduction.

  make_results_check.py COMMITTED_OUTPUT_DIR OUT_JSON
"""
import json
import sys
from pathlib import Path

committed, out = sys.argv[1:3]
comp = json.load(open(Path(committed) / "comparison.json"))
results = []
for it in comp["item_list"]:
    for i, f in enumerate(it["fields"]):
        e = {"id": f"{it['id']}.{i}", "label": f"{it['id']}, {f['name']} (paper {f['expected']})",
             "file": "comparison.json", "path": f"item_list.key={it['key']}.fields.{i}.observed",
             "expected": f["observed"]}
        if isinstance(f["observed"], float):
            e["tolerance"] = {"rel": 1e-9}
        results.append(e)
doc = {"paper": "PMC2563693",
       "title": "Lee E, Chuang HY, Kim JW, Ideker T, Lee D. Inferring pathway activity toward precise disease classification. PLoS Comput Biol 4(11):e1000217 (2008)",
       "about": "Our value for every published number the reproduction compares (figure values, table entries, claims). CI reruns the pipeline (two cross-validation repeats per experiment from scratch; the rest from the committed full run in output/cv) and checks each value with tools/check_results.py. Generated by pipeline/make_results_check.py from the committed comparison.json.",
       "committed_paths": {"": "output/"},
       "results": results}
Path(out).write_text(json.dumps(doc, indent=2) + "\n")
print(f"{len(results)} entries")
