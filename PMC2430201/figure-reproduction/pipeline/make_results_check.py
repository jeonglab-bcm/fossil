"""Write figure-reproduction/results.json, the repository's results-check file (tools/check_results.py):
every value our run gives for a printed table cell or a claim becomes an entry whose expected value is the
committed output, so CI catches any drift.

Usage: make_results_check.py OUTPUT_DIR OUT_JSON
"""
import json
import sys
from pathlib import Path

out_dir, out = Path(sys.argv[1]), sys.argv[2]
comp = json.load(open(out_dir / "comparison.json"))
claims = json.load(open(out_dir / "claims.json"))
NUM = {"rel": 1e-9, "abs": 1e-12}
results = []


def add(id_, label, file, path, value):
    e = {"id": id_, "label": label, "file": file, "path": path, "expected": value}
    if isinstance(value, float):
        e["tolerance"] = NUM
    results.append(e)


for t, block in comp["tables"].items():
    for i, f in enumerate(block["fields"]):
        add(f"table{t}.{i}", f"Table {t}, {f['name']} (paper {f['expected']})", "comparison.json", f"tables.{t}.fields.{i}.observed", f["observed"])
for cid, c in claims.items():
    if cid.startswith("_"):
        continue
    for i, f in enumerate(c["fields"]):
        add(f"{cid}.{i}", f"{cid}, {f['name']} (paper {f['expected']})", "claims.json", f"{cid}.fields.{i}.observed", f["observed"])
add("crosscheck.passed", "rommeta's pooling equals metafor's on 900 simulated meta-analyses", "crosscheck.json", "pooling.passed", True)
doc = {"paper": "PMC2430201",
       "title": "Friedrich JO, Adhikari NKJ, Beyene J. The ratio of means method as an alternative to mean differences for analyzing continuous outcome variables in meta-analysis: a simulation study. BMC Medical Research Methodology 8:32 (2008)",
       "about": "Our value for every printed cell of Tables 3-8 and every claim the reproduction compares. CI reruns the whole pipeline and checks each value with tools/check_results.py. Generated by pipeline/make_results_check.py from the committed outputs.",
       "committed_paths": {"": "output/"},
       "results": results}
Path(out).write_text(json.dumps(doc, indent=1) + "\n")
print(f"{out}: {len(results)} entries", file=sys.stderr)
