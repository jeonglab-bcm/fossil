"""Write figure-reproduction/results.json, the repository's results-check file (tools/check_results.py):
every value our run gives for a cell of Tables 1-3, a claim, or a number of the mini run becomes an
entry whose expected value is the committed output, so CI catches any drift.

Usage: make_results_check.py OUTPUT_DIR OUT_JSON
"""
import json
import sys
from pathlib import Path

out_dir, out = Path(sys.argv[1]), sys.argv[2]
comp = json.load(open(out_dir / "comparison.json"))
NUM = {"rel": 1e-9, "abs": 1e-12}
results = []


def add(id_, label, file, path, value, tol=NUM):
    e = {"id": id_, "label": label, "file": file, "path": path, "expected": value}
    if isinstance(value, float):
        e["tolerance"] = tol
    results.append(e)


for t, block in comp["tables"].items():
    for i, f in enumerate(block["fields"]):
        add(f"{t}.{i}", f"{t}, {f['name']} (paper {f['expected']})", "comparison.json", f"tables.{t}.fields.{i}.observed", f["observed"])
for cid, c in comp["claims"].items():
    if cid.startswith("_"):
        continue
    for i, f in enumerate(c["fields"]):
        if f["observed"] is None:
            continue
        add(f"{cid}.{i}", f"{cid}, {f['name']} (paper {f['expected']})", "comparison.json", f"claims.{cid}.fields.{i}.observed", f["observed"])
mini = json.load(open(out_dir / "mini" / "models.json"))
for kind, models in mini["models"].items():
    for name, m in models.items():
        for yr in ("2011", "2012"):
            for k in ("auc", "average_precision", "f1", "mse"):
                add(f"mini.{kind}.{name}.{yr}.{k}", f"mini run, {kind}, {name}, {yr}, {k}", "mini/models.json",
                    f"models.{kind}.{name}.{yr}.{k}", m[yr][k], {"rel": 1e-6, "abs": 1e-9})
doc = {"paper": "PMC4457112",
       "title": "Cohen AM, Smalheiser NR, McDonagh MS, Yu C, Adams CE, Davis JM, Yu PS. Automated confidence ranked classification of randomized controlled trial articles: an aid to evidence-based medicine. J Am Med Inform Assoc 22(3):707-717 (2015)",
       "about": "Our value for every cell of Tables 1-3 and every claim the reproduction compares (from the committed full run), and the measures of the mini run that CI repeats. Generated by pipeline/make_results_check.py from the committed outputs.",
       "committed_paths": {"": "output/"},
       "results": results}
Path(out).write_text(json.dumps(doc, indent=1) + "\n")
print(f"{out}: {len(results)} entries", file=sys.stderr)
