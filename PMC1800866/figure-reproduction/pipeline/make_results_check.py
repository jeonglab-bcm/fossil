#!/usr/bin/env python3
"""Write figure-reproduction/results.json, the repository's results-check file (tools/check_results.py),
from results_notes.json: every value field read from a run file and every pixel score becomes an
entry whose expected value is the committed output, so CI catches any drift.

Usage: make_results_check.py COMMITTED_OUTPUT_DIR OUT_JSON
"""
import json
import sys
from pathlib import Path

from build_results import NOTES, lookup


def main(committed, out):
    notes = json.load(open(NOTES))
    results = []
    for it in notes["items"]:
        refs = []
        for f in (it.get("values") or {}).get("fields", []):
            if "observed_from" in f and "observed_map" not in f:
                refs.append((f["name"], f["observed_from"], f.get("expected")))
        if "pixels_from" in it:
            fpath, _, p = it["pixels_from"].partition(":")
            for k in ("published_near_ours", "ours_near_published"):
                refs.append((k.replace("_", " "), f"{fpath}:{p}.{k}", None))
        for name, ref, paper in refs:
            fpath, _, path = ref.partition(":")
            v = lookup(committed, ref)
            entry = {"id": f"{it['id']}.{name}".replace(" ", "_").replace("{", "").replace("}", "").replace(",", "-"),
                     "label": f"{it['label']}, {name}" + (f" (paper {paper})" if paper is not None else ""),
                     "file": fpath, "path": path, "expected": v}
            if isinstance(v, float):
                entry["tolerance"] = {"rel": 1e-6, "abs": 1e-9}
            results.append(entry)
    doc = {"paper": "PMC1800866",
           "title": notes["paper"]["citation"],
           "about": "The results this reproduction stands on. CI reruns the pipeline (the five-fold CV, the figures, the proteome sample scan; the leave-one-out predictions are read from output/predictions) and checks each value with tools/check_results.py. Generated by pipeline/make_results_check.py from results_notes.json and the committed outputs.",
           "committed_paths": {"": "output/"},
           "results": results}
    Path(out).write_text(json.dumps(doc, indent=2) + "\n")
    print(f"{len(results)} entries")


if __name__ == "__main__":
    main(*sys.argv[1:3])
