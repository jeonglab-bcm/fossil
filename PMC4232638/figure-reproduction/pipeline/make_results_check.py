"""Write figure-reproduction/results.json, the repository's results-check file (tools/check_results.py):
every value our run gives for a printed or drawn number of the paper (each field of comparison.json and
claims.json, and the summaries of the per-combination check against Additional files 17 and 18) becomes
an entry whose expected value is the committed output, so CI catches any drift.

Usage: make_results_check.py OUTPUT_DIR OUT_JSON
"""
import json
import sys
from pathlib import Path

out_dir, out = Path(sys.argv[1]), sys.argv[2]
comp = json.load(open(out_dir / "comparison.json"))
claims = json.load(open(out_dir / "claims.json"))
NUM = {"rel": 1e-9, "abs": 1e-12}
results = []


def add(id_, label, file, path, value):
    if value is None:
        return
    e = {"id": id_, "label": label, "file": file, "path": path, "expected": value}
    if isinstance(value, float):
        e["tolerance"] = NUM
    results.append(e)


for key, block in comp.items():
    if not isinstance(block, dict):
        continue
    fields = block.get("fields", [])
    for i, f in enumerate(fields if isinstance(fields, list) else []):
        add(f"{key}.{i}", f"{key}, {f['name']} (paper {f['expected']})", "comparison.json", f"{key}.fields.{i}.observed", f["observed"])
for key in ("af17", "af18"):
    for part in ("means_within", "intervals_within"):
        add(f"{key}.{part}", f"{key}, {part.replace('_', ' ')}", "comparison.json", f"{key}.summary.{part}", comp[key]["summary"][part])
for cid, c in claims.items():
    for i, f in enumerate(c["fields"]):
        add(f"{cid}.{i}", f"{cid}, {f['name']} (paper {f['expected']})", "claims.json", f"{cid}.fields.{i}.observed", f["observed"])
doc = {"paper": "PMC4232638",
       "title": "Martelotto LG, Ng CKY, De Filippo MR, et al. Benchmarking mutation effect prediction algorithms using functionally validated cancer-related missense mutations. Genome Biology 15:484 (2014)",
       "about": "Our value for every printed cell of Tables 1-4 and Additional files 3, 5, 8, 9, 11, 13, 16, 19, 21, 22, 25, 27 and 28, every value read from Figs 1-4, the per-combination check of Additional files 17 and 18, and every claim the reproduction compares. CI reruns the whole pipeline and checks each value with tools/check_results.py. Generated by pipeline/make_results_check.py from the committed outputs.",
       "committed_paths": {"": "output/"},
       "results": results}
Path(out).write_text(json.dumps(doc, indent=1) + "\n")
print(f"{out}: {len(results)} entries", file=sys.stderr)
