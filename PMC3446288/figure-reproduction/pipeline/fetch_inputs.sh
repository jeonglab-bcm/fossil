#!/usr/bin/env bash
# Download the inputs of the PMC3446288 reproduction and check their SHA-256.
#
#   fetch_inputs.sh OUTDIR [--full] [--sources DIR]
#
# Default (what CI needs): the UCSC mm9 annotation tables, the mm9 genome (chromFa.tar.gz, unpacked
# into one FASTA of the 22 chromosomes the Bowtie index has, with a .fai index) and the paper's
# supplementary files (Additional files 1 to 12, for the PTC-distance check).
# --full adds what the mapping and conservation steps need: the four SRA runs, the Illumina iGenomes
# mm9 Bowtie index, the GEO GSE26561 TopHat alignments and the mm9 phastCons30way scores (about 9 GB).
# --sources DIR takes files from DIR (same layout as OUTDIR) instead of downloading them.
set -euo pipefail
out="$1"; shift
full=0; src=""
while [ $# -gt 0 ]; do
  case "$1" in
    --full) full=1 ;;
    --sources) src="$2"; shift ;;
  esac
  shift
done
mkdir -p "$out"/{annot,genome,supp,sra,geo,phastcons}

UCSC=https://hgdownload.soe.ucsc.edu/goldenPath/mm9
fetch() {  # fetch URL DEST SHA256 [MIRROR]
  local url="$1" dest="$2" sum="$3" mirror="${4:-}"
  local rel="${dest#$out/}"
  if [ -n "$src" ] && [ -f "$src/$rel" ]; then cp "$src/$rel" "$dest"
  elif [ ! -f "$dest" ]; then
    curl -fsSL --retry 3 --retry-delay 5 -o "$dest" "$url" || { [ -n "$mirror" ] && curl -fsSL --retry 3 -o "$dest" "$mirror"; }
  fi
  echo "$sum  $dest" | sha256sum -c --quiet - || { echo "checksum failed: $dest" >&2; exit 1; }
}

# UCSC mm9 annotation tables (the files are regenerated by UCSC from time to time; the sums pin the
# versions we used: refGene 2020-08-22, knownGene 2011-05-30, ensGene 2011-11-14, genscan and exoniphy 2007)
fetch $UCSC/database/refGene.txt.gz   "$out/annot/refGene.txt.gz"   7eb239607afa72581e1eebb9c90156e8d83d871953118357b93d39df88208ac4
fetch $UCSC/database/knownGene.txt.gz "$out/annot/knownGene.txt.gz" 3fc130914933241214bac67245893368d32555be712682ee5043b746f8703824
fetch $UCSC/database/ensGene.txt.gz   "$out/annot/ensGene.txt.gz"   76a0450c3ceb6d6e825d37722a0727cf0b5bab61f017e50f9cc5b1e7da0101bf
fetch $UCSC/database/genscan.txt.gz   "$out/annot/genscan.txt.gz"   e49d3f2f854ab664bd535e1cf652c262a756be65157f2396181f851e65058a0e
fetch $UCSC/database/exoniphy.txt.gz  "$out/annot/exoniphy.txt.gz"  d7f3c387dd840bc7c8c508e1fd8410b32777efa7bc19c7b00679e9048590fb0b

# mm9 genome: the 22 chromosomes of the iGenomes Bowtie index, in its order
if [ -n "$src" ] && [ -f "$src/genome/mm9.fa.fai" ]; then
  ln -sf "$(readlink -f "$src/genome/mm9.fa")" "$out/genome/mm9.fa"
  ln -sf "$(readlink -f "$src/genome/mm9.fa.fai")" "$out/genome/mm9.fa.fai"
fi
[ -f "$out/genome/mm9.fa.fai" ] || fetch $UCSC/bigZips/chromFa.tar.gz "$out/genome/chromFa.tar.gz" f037985ab61683a93a0ffe58a82c2515bfdcede981a67fde78265e4bbef57f70
if [ ! -f "$out/genome/mm9.fa.fai" ]; then
  tmp="$out/genome/chroms"; mkdir -p "$tmp"
  tar -xzf "$out/genome/chromFa.tar.gz" -C "$tmp"
  for c in chr10 chr11 chr12 chr13 chr14 chr15 chr16 chr17 chr18 chr19 chr1 chr2 chr3 chr4 chr5 chr6 chr7 chr8 chr9 chrM chrX chrY; do
    cat "$tmp/$c.fa"
  done > "$out/genome/mm9.fa"
  rm -rf "$tmp" "$out/genome/chromFa.tar.gz"
  python3 -c "import pysam,sys; pysam.faidx(sys.argv[1])" "$out/genome/mm9.fa"
fi

# The paper's supplementary files (PMC open-access copy on AWS; Europe PMC as the fallback)
PMC=https://pmc-oa-opendata.s3.amazonaws.com/PMC3446288.1
SUPP_SUMS="gb-2012-13-5-r35-S1.DOC ace6a5cbeadef849b52cb122928b9925fbfa5751ca0354b6a835cc95e5d38fec
gb-2012-13-5-r35-S12.XLS ca01da5db3f46ea89fe8ba77faceb8ea7892a962eacbdef320934c29e74a94cd
gb-2012-13-5-r35-S8.XLS a684b085ee3a446745dd3b8c9df7ae85f5a4049034374723fca9b9e3a209d345
gb-2012-13-5-r35-S9.XLS f1d48bb6d16a20c3c3eb8d09845e1586629a2e56d44761e0f76d561722cca352
gb-2012-13-5-r35-S4.XLSX 2cafe724a19d73dba503538f740fa1653c5e6c990defc9be4981b9cdf2ba0958
gb-2012-13-5-r35-S5.XLSX 89d835c53d819e42596d5738ae4981973a4decbcfe7f49a384d0bd183d26c07e
gb-2012-13-5-r35-S6.XLSX cc760821114a880c9505ab9afb1b6bba955c898efe66cfa5fda684acaee7100b"
while read -r name sum; do
  [ -z "$name" ] && continue
  fetch "$PMC/$name" "$out/supp/$name" "$sum"
done <<< "$SUPP_SUMS"

[ "$full" = 1 ] || exit 0

# Reads: SRA normalized runs on AWS
