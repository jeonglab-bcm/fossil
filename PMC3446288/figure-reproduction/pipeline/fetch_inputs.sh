  fetch "https://sra-pub-run-odp.s3.amazonaws.com/sra/$r/$r" "$out/sra/$r.sra" "$sum"
done
# Bowtie index of mm9 (Illumina iGenomes)
IG=https://ngi-igenomes.s3.amazonaws.com/igenomes/Mus_musculus/UCSC/mm9/Sequence/BowtieIndex
